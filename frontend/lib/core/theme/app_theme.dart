import 'package:flex_color_scheme/flex_color_scheme.dart';
import 'package:flutter/material.dart';

import '../constants/app_constants.dart';

class AppTheme {
  /// The typeface every style below is built from: Inter, the one family the
  /// design system names for anything user-facing (design/tokens.json,
  /// `typography.family.ui`).
  ///
  /// It is a bundled asset -- `assets/fonts/Inter-*.ttf`, declared with their
  /// weights in pubspec.yaml -- not a runtime download. google_fonts used to
  /// fetch it from fonts.gstatic.com on first paint, which worked on the web
  /// but meant the first frame was never the design system's, the offline
  /// desktop build had no way to get the typeface at all, and every weight
  /// arrived as its own one-face family so `copyWith(fontWeight: ...)`
  /// resolved to a synthesised face. See pubspec.yaml for the full note.
  ///
  /// Naming only the family (not a per-weight family) is what lets Flutter
  /// pick the real 400/500/600/700 face for whatever weight is asked for,
  /// here or in any `copyWith` downstream.
  static TextStyle font({
    Color? color,
    double? fontSize,
    FontWeight? fontWeight,
    double? letterSpacing,
  }) =>
      TextStyle(
        fontFamily: AppConstants.fontFamily,
        color: color,
        fontSize: fontSize,
        fontWeight: fontWeight,
        letterSpacing: letterSpacing,
      );

  /// Colour roles are generated by FlexColorScheme rather than hand-picked, so
  /// containers, outlines and on-colours stay contrast-safe across light and
  /// dark. The component themes below are kept as-is — only the palette changes.
  static ColorScheme _scheme(Brightness brightness) => SeedColorScheme.fromSeeds(
        brightness: brightness,
        primaryKey: const Color(AppConstants.primaryColorValue),
        secondaryKey: const Color(AppConstants.secondaryColorValue),
        tertiaryKey: const Color(AppConstants.accentColorValue),
        tones: FlexTones.material(brightness),
      );

  static const Color _primary = Color(AppConstants.primaryColorValue);
  static const Color _secondary = Color(AppConstants.secondaryColorValue);
  static const Color _accent = Color(AppConstants.accentColorValue);
  static const Color _success = Color(AppConstants.successColorValue);
  static const Color _warning = Color(AppConstants.warningColorValue);
  static const Color _error = Color(AppConstants.errorColorValue);
  static const Color _surface = Color(AppConstants.surfaceColorValue);
  static const Color _background = Color(AppConstants.backgroundColorValue);
  
  static const Color _onPrimary = Colors.white;
  static const Color _onSecondary = Colors.white;
  static const Color _onSurface = Color(0xFF1E293B);
  static const Color _onBackground = Color(0xFF1E293B);
  
  // Light theme
  static ThemeData get lightTheme => ThemeData(
    useMaterial3: true,
    brightness: Brightness.light,
    colorScheme: _scheme(Brightness.light),
    textTheme: _textTheme(brightness: Brightness.light),
    appBarTheme: AppBarTheme(
      elevation: 0,
      centerTitle: true,
      backgroundColor: _surface,
      foregroundColor: _onSurface,
      titleTextStyle: font(
        fontSize: 20,
        fontWeight: FontWeight.w600,
        color: _onSurface,
      ),
    ),
    cardTheme: CardThemeData(
      elevation: AppConstants.cardElevation,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
      ),
      color: _surface,
      shadowColor: _primary.withValues(alpha: 0.1),
    ),
    elevatedButtonTheme: ElevatedButtonThemeData(
      style: ElevatedButton.styleFrom(
        backgroundColor: _primary,
        foregroundColor: _onPrimary,
        elevation: 0,
        padding: const EdgeInsets.symmetric(
          horizontal: 24,
          vertical: 14,
        ),
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        ),
        textStyle: font(
          fontSize: 14,
          fontWeight: FontWeight.w600,
        ),
      ),
    ),
    outlinedButtonTheme: OutlinedButtonThemeData(
      style: OutlinedButton.styleFrom(
        foregroundColor: _primary,
        side: const BorderSide(color: _primary, width: 1.5),
        padding: const EdgeInsets.symmetric(
          horizontal: 24,
          vertical: 14,
        ),
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        ),
        textStyle: font(
          fontSize: 14,
          fontWeight: FontWeight.w600,
        ),
      ),
    ),
    textButtonTheme: TextButtonThemeData(
      style: TextButton.styleFrom(
        foregroundColor: _primary,
        padding: const EdgeInsets.symmetric(
          horizontal: 16,
          vertical: 10,
        ),
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        ),
        textStyle: font(
          fontSize: 14,
          fontWeight: FontWeight.w500,
        ),
      ),
    ),
    inputDecorationTheme: InputDecorationTheme(
      filled: true,
      fillColor: _surface,
      contentPadding: const EdgeInsets.symmetric(
        horizontal: 16,
        vertical: 14,
      ),
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: BorderSide(color: _primary.withValues(alpha: 0.3)),
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: BorderSide(color: _primary.withValues(alpha: 0.3)),
      ),
      focusedBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: const BorderSide(color: _primary, width: 2),
      ),
      errorBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: const BorderSide(color: _error, width: 1.5),
      ),
      labelStyle: font(color: _onSurface.withValues(alpha: 0.7)),
      hintStyle: font(color: _onSurface.withValues(alpha: 0.4)),
    ),
    chipTheme: ChipThemeData(
      backgroundColor: _primary.withValues(alpha: 0.1),
      selectedColor: _primary,
      labelStyle: font(
        color: _primary,
        fontWeight: FontWeight.w500,
      ),
      secondaryLabelStyle: font(
        color: _onPrimary,
        fontWeight: FontWeight.w500,
      ),
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(20),
      ),
    ),
    tabBarTheme: TabBarThemeData(
      labelColor: _primary,
      unselectedLabelColor: _onSurface.withValues(alpha: 0.5),
      indicatorColor: _primary,
      indicatorSize: TabBarIndicatorSize.label,
      labelStyle: font(fontWeight: FontWeight.w600),
      unselectedLabelStyle: font(fontWeight: FontWeight.w500),
    ),
    navigationBarTheme: NavigationBarThemeData(
      backgroundColor: _surface,
      indicatorColor: _primary.withValues(alpha: 0.1),
      labelTextStyle: WidgetStateProperty.resolveWith((states) {
        if (states.contains(WidgetState.selected)) {
          return font(
            color: _primary,
            fontWeight: FontWeight.w600,
            fontSize: 12,
          );
        }
        return font(
          color: _onSurface.withValues(alpha: 0.6),
          fontWeight: FontWeight.w500,
          fontSize: 12,
        );
      }),
    ),
    dividerTheme: DividerThemeData(
      color: _primary.withValues(alpha: 0.1),
      thickness: 1,
      space: 1,
    ),
    listTileTheme: ListTileThemeData(
      contentPadding: const EdgeInsets.symmetric(
        horizontal: AppConstants.defaultPadding,
        vertical: 4,
      ),
      titleTextStyle: font(
        fontSize: 16,
        fontWeight: FontWeight.w500,
        color: _onSurface,
      ),
      subtitleTextStyle: font(
        fontSize: 13,
        color: _onSurface.withValues(alpha: 0.6),
      ),
      leadingAndTrailingTextStyle: font(
        fontSize: 14,
        color: _onSurface.withValues(alpha: 0.7),
      ),
    ),
    scaffoldBackgroundColor: _background,
    pageTransitionsTheme: const PageTransitionsTheme(
      builders: {
        TargetPlatform.android: ZoomPageTransitionsBuilder(),
        TargetPlatform.iOS: FadeForwardsPageTransitionsBuilder(),
        TargetPlatform.windows: ZoomPageTransitionsBuilder(),
        TargetPlatform.macOS: ZoomPageTransitionsBuilder(),
        TargetPlatform.linux: ZoomPageTransitionsBuilder(),
      },
    ),
  );
  
  // Dark theme
  static ThemeData get darkTheme => ThemeData(
    useMaterial3: true,
    brightness: Brightness.dark,
    colorScheme: _scheme(Brightness.dark),
    textTheme: _textTheme(brightness: Brightness.dark),
    appBarTheme: AppBarTheme(
      elevation: 0,
      centerTitle: true,
      backgroundColor: const Color(0xFF1E293B),
      foregroundColor: const Color(0xFFF1F5F9),
      titleTextStyle: font(
        fontSize: 20,
        fontWeight: FontWeight.w600,
        color: const Color(0xFFF1F5F9),
      ),
    ),
    cardTheme: CardThemeData(
      elevation: AppConstants.cardElevation,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
      ),
      color: const Color(0xFF1E293B),
      shadowColor: Colors.black.withValues(alpha: 0.3),
    ),
    elevatedButtonTheme: ElevatedButtonThemeData(
      style: ElevatedButton.styleFrom(
        backgroundColor: const Color(0xFF60A5FA),
        foregroundColor: const Color(0xFF0F172A),
        elevation: 0,
        padding: const EdgeInsets.symmetric(
          horizontal: 24,
          vertical: 14,
        ),
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        ),
        textStyle: font(
          fontSize: 14,
          fontWeight: FontWeight.w600,
        ),
      ),
    ),
    outlinedButtonTheme: OutlinedButtonThemeData(
      style: OutlinedButton.styleFrom(
        foregroundColor: const Color(0xFF60A5FA),
        side: const BorderSide(color: Color(0xFF60A5FA), width: 1.5),
        padding: const EdgeInsets.symmetric(
          horizontal: 24,
          vertical: 14,
        ),
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        ),
        textStyle: font(
          fontSize: 14,
          fontWeight: FontWeight.w600,
        ),
      ),
    ),
    inputDecorationTheme: InputDecorationTheme(
      filled: true,
      fillColor: const Color(0xFF1E293B),
      contentPadding: const EdgeInsets.symmetric(
        horizontal: 16,
        vertical: 14,
      ),
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: BorderSide(color: const Color(0xFF60A5FA).withValues(alpha: 0.3)),
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: BorderSide(color: const Color(0xFF60A5FA).withValues(alpha: 0.3)),
      ),
      focusedBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: const BorderSide(color: Color(0xFF60A5FA), width: 2),
      ),
      errorBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AppConstants.borderRadius),
        borderSide: const BorderSide(color: Color(0xFFF87171), width: 1.5),
      ),
      labelStyle: font(color: const Color(0xFF94A3B8)),
      hintStyle: font(color: const Color(0xFF64748B)),
    ),
    chipTheme: ChipThemeData(
      backgroundColor: const Color(0xFF60A5FA).withValues(alpha: 0.15),
      selectedColor: const Color(0xFF60A5FA),
      labelStyle: font(
        color: const Color(0xFF60A5FA),
        fontWeight: FontWeight.w500,
      ),
      secondaryLabelStyle: font(
        color: const Color(0xFF0F172A),
        fontWeight: FontWeight.w500,
      ),
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(20),
      ),
    ),
    tabBarTheme: TabBarThemeData(
      labelColor: const Color(0xFF60A5FA),
      unselectedLabelColor: const Color(0xFF94A3B8),
      indicatorColor: const Color(0xFF60A5FA),
      indicatorSize: TabBarIndicatorSize.label,
      labelStyle: font(fontWeight: FontWeight.w600),
      unselectedLabelStyle: font(fontWeight: FontWeight.w500),
    ),
    navigationBarTheme: NavigationBarThemeData(
      backgroundColor: const Color(0xFF1E293B),
      indicatorColor: const Color(0xFF60A5FA).withValues(alpha: 0.15),
      labelTextStyle: WidgetStateProperty.resolveWith((states) {
        if (states.contains(WidgetState.selected)) {
          return font(
            color: const Color(0xFF60A5FA),
            fontWeight: FontWeight.w600,
            fontSize: 12,
          );
        }
        return font(
          color: const Color(0xFF94A3B8),
          fontWeight: FontWeight.w500,
          fontSize: 12,
        );
      }),
    ),
    dividerTheme: DividerThemeData(
      color: const Color(0xFF60A5FA).withValues(alpha: 0.1),
      thickness: 1,
      space: 1,
    ),
    listTileTheme: ListTileThemeData(
      contentPadding: const EdgeInsets.symmetric(
        horizontal: AppConstants.defaultPadding,
        vertical: 4,
      ),
      titleTextStyle: font(
        fontSize: 16,
        fontWeight: FontWeight.w500,
        color: const Color(0xFFF1F5F9),
      ),
      subtitleTextStyle: font(
        fontSize: 13,
        color: const Color(0xFF94A3B8),
      ),
      leadingAndTrailingTextStyle: font(
        fontSize: 14,
        color: const Color(0xFF94A3B8),
      ),
    ),
    scaffoldBackgroundColor: const Color(0xFF0F172A),
    pageTransitionsTheme: const PageTransitionsTheme(
      builders: {
        TargetPlatform.android: ZoomPageTransitionsBuilder(),
        TargetPlatform.iOS: FadeForwardsPageTransitionsBuilder(),
        TargetPlatform.windows: ZoomPageTransitionsBuilder(),
        TargetPlatform.macOS: ZoomPageTransitionsBuilder(),
        TargetPlatform.linux: ZoomPageTransitionsBuilder(),
      },
    ),
  );
  
  static TextTheme _textTheme({required Brightness brightness}) {
    final isDark = brightness == Brightness.dark;
    final onSurface = isDark ? const Color(0xFFF1F5F9) : const Color(0xFF1E293B);
    final onSurfaceVariant = isDark 
        ? const Color(0xFF94A3B8) 
        : const Color(0xFF64748B);
    
    return TextTheme(
      displayLarge: font(
        fontSize: 57,
        fontWeight: FontWeight.w400,
        color: onSurface,
        letterSpacing: -0.25,
      ),
      displayMedium: font(
        fontSize: 45,
        fontWeight: FontWeight.w400,
        color: onSurface,
      ),
      displaySmall: font(
        fontSize: 36,
        fontWeight: FontWeight.w400,
        color: onSurface,
      ),
      headlineLarge: font(
        fontSize: 32,
        fontWeight: FontWeight.w600,
        color: onSurface,
      ),
      headlineMedium: font(
        fontSize: 28,
        fontWeight: FontWeight.w600,
        color: onSurface,
      ),
      headlineSmall: font(
        fontSize: 24,
        fontWeight: FontWeight.w600,
        color: onSurface,
      ),
      titleLarge: font(
        fontSize: 22,
        fontWeight: FontWeight.w600,
        color: onSurface,
        letterSpacing: 0,
      ),
      titleMedium: font(
        fontSize: 16,
        fontWeight: FontWeight.w600,
        color: onSurface,
        letterSpacing: 0.15,
      ),
      titleSmall: font(
        fontSize: 14,
        fontWeight: FontWeight.w600,
        color: onSurface,
        letterSpacing: 0.1,
      ),
      bodyLarge: font(
        fontSize: 16,
        fontWeight: FontWeight.w400,
        color: onSurface,
        letterSpacing: 0.5,
      ),
      bodyMedium: font(
        fontSize: 14,
        fontWeight: FontWeight.w400,
        color: onSurface,
        letterSpacing: 0.25,
      ),
      bodySmall: font(
        fontSize: 12,
        fontWeight: FontWeight.w400,
        color: onSurfaceVariant,
        letterSpacing: 0.4,
      ),
      labelLarge: font(
        fontSize: 14,
        fontWeight: FontWeight.w500,
        color: onSurface,
        letterSpacing: 0.1,
      ),
      labelMedium: font(
        fontSize: 12,
        fontWeight: FontWeight.w500,
        color: onSurfaceVariant,
        letterSpacing: 0.5,
      ),
      labelSmall: font(
        fontSize: 11,
        fontWeight: FontWeight.w500,
        color: onSurfaceVariant,
        letterSpacing: 0.5,
      ),
    ).apply(
      fontFamily: AppConstants.fontFamily,
      displayColor: onSurface,
      bodyColor: onSurface,
    );
  }
}
