import '../../core/local_engine/local_store.dart';

/// English and Hindi for the School pages and the phone apps (TA-9, SA).
///
/// The English text is the key, so a string with no Hindi yet still reads
/// correctly. The choice is per device (a shared family phone keeps its
/// own), set from the School page's language button.
const _key = 'ui_language';

bool get uiHindi {
  try {
    return LocalStore.instance.box.get(_key) == 'hi';
  } catch (_) {
    // not-a-failure: before the local store opens (tests, first frame) the language is English
    return false;
  }
}

void setUiLanguage(String code) => LocalStore.instance.box.put(_key, code);

/// Which screens Hindi covers, said wherever the language is chosen. The
/// School page offered "हिन्दी में देखें" while Settings listed English only,
/// "not translated yet", and kept a setting of its own that nothing read
/// (QA S-16). Both now change the one setting above and say the same.
const hindiCoverage = 'Hindi covers the phone apps\' screens: the School page and its tiles, Today, My day, '
    'My week, homework, leave and cover, the inbox, the family pages and the Papers list. The side menu, '
    'the paper builder, the term report, the admin console and Settings stay in English for now.';

String tr(String en) => uiHindi ? (_hi[en] ?? en) : en;

/// [tr] for a sentence that carries values: the English is a template with
/// `{name}` placeholders, translated whole and then filled. Joining fragments
/// around a value ("Due " + date) cannot be translated: Hindi puts the verb
/// last and moves the value ("{date} तक जमा करें").
String trf(String en, Map<String, Object?> args) {
  var out = tr(en);
  args.forEach((k, v) => out = out.replaceAll('{$k}', '${v ?? ''}'));
  return out;
}

/// Whether [en] has a Hindi entry: the coverage test reads it (R-B5).
bool hasHindi(String en) => _hi.containsKey(en);

