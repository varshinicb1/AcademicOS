"""R-A1: SQLite-shaped connections over Postgres (storage/pg_sqlite.py).

The translation tests need no database. The behaviour tests run against a real Postgres when
ACOS_STORE_PG_HOST (or ACOS_TEST_PG_HOST) is set, and skip otherwise; the whole suite also runs with
ACOS_STORE_BACKEND=postgres, which is the real proof that the stores work there.
"""
from __future__ import annotations

import os
import sqlite3
import uuid

import pytest

from academicos.storage import pg_sqlite
from academicos.storage.pg_sqlite import split_script, translate


# ---- translation -------------------------------------------------------------------------------

def test_placeholders_and_percent_signs_but_not_inside_strings():
    t = translate("SELECT * FROM t WHERE a=? AND b LIKE '50%?' AND c=?")
    assert t.sql == "SELECT * FROM t WHERE a=%s AND b ILIKE '50%%?' AND c=%s"


def test_is_parameter_becomes_is_distinct_from():
    assert translate("SELECT 1 FROM t WHERE a IS ? AND b IS NOT ?").sql == \
        "SELECT 1 FROM t WHERE a IS NOT DISTINCT FROM %s AND b IS DISTINCT FROM %s"


def test_order_by_puts_nulls_where_sqlite_does():
    t = translate("SELECT * FROM t ORDER BY a, b DESC, c ASC LIMIT ?")
    assert t.sql == "SELECT * FROM t ORDER BY a NULLS FIRST, b DESC NULLS LAST, c ASC NULLS FIRST LIMIT %s"
    # A subquery's ORDER BY ends at its closing parenthesis.
    t = translate("SELECT * FROM t WHERE id IN (SELECT id FROM u ORDER BY seq) ORDER BY x")
    assert t.sql == "SELECT * FROM t WHERE id IN (SELECT id FROM u ORDER BY seq NULLS FIRST) ORDER BY x NULLS FIRST"


def test_two_argument_max_and_min_are_greatest_and_least():
    t = translate("SELECT max(a, b), min(c, 1), max(d) FROM t")
    assert t.sql == "SELECT GREATEST(a, b), LEAST(c, 1), max(d) FROM t"


def test_insert_or_ignore_and_upsert_qualification():
    assert translate("INSERT OR IGNORE INTO t (a, b) VALUES (?, ?)").sql == \
        "INSERT INTO t (a, b) VALUES (%s, %s) ON CONFLICT DO NOTHING"
    assert translate("INSERT INTO t (a) VALUES (?) ON CONFLICT(a) DO UPDATE SET n = n + 1, m = excluded.m").sql == \
        "INSERT INTO t (a) VALUES (%s) ON CONFLICT(a) DO UPDATE SET n = t.n + 1, m = excluded.m"


def test_insert_or_replace_is_resolved_against_the_primary_key():
    t = translate("INSERT OR REPLACE INTO runs (job, period_key, ran_at) VALUES (?,?,?)")
    assert t.replace_into == ("runs", ["job", "period_key", "ran_at"])
    assert t.sql == "INSERT INTO runs (job, period_key, ran_at) VALUES (%s,%s,%s)"


def test_ddl_types_collations_and_the_hidden_rowid():
    sql = translate("CREATE TABLE IF NOT EXISTS t (\n  id INTEGER PRIMARY KEY AUTOINCREMENT,\n"
                    "  name TEXT NOT NULL COLLATE NOCASE,\n  note TEXT,\n  score REAL,\n  n INTEGER,\n"
                    "  UNIQUE(name, n)\n)").sql
    assert "rowid BIGINT GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "name TEXT NOT NULL COLLATE nocase" in sql
    assert 'note TEXT COLLATE "C"' in sql
    assert "score DOUBLE PRECISION" in sql and "n BIGINT" in sql
    assert "UNIQUE(name, n)" in sql
    assert translate("ALTER TABLE t ADD COLUMN end_date TEXT").sql == 'ALTER TABLE t ADD COLUMN end_date TEXT COLLATE "C"'


def test_pragmas_and_rowid_selection():
    assert translate("PRAGMA journal_mode=WAL").noop
    assert translate("PRAGMA table_info(holidays)").table_info == "holidays"
    assert not translate("SELECT * FROM t ORDER BY seq, rowid").names_rowid
    assert translate("SELECT rowid, id FROM t").names_rowid


def test_a_script_splits_on_semicolons_outside_strings_and_comments():
    script = "CREATE TABLE a (x TEXT DEFAULT ';'); -- a; comment\nCREATE TABLE b (y TEXT);\n"
    assert [s.strip() for s in split_script(script)] == \
        ["CREATE TABLE a (x TEXT DEFAULT ';')", "-- a; comment\nCREATE TABLE b (y TEXT)"]


def test_schema_names_come_from_the_environment_or_the_path(tmp_path, monkeypatch):
    monkeypatch.delenv("ACOS_PG_SCHEMA_CURRICULUM", raising=False)
    a, b = pg_sqlite.schema_for("curriculum", tmp_path / "a.sqlite"), pg_sqlite.schema_for("curriculum", tmp_path / "b.sqlite")
    assert a.startswith("curriculum_") and a != b
    monkeypatch.setenv("ACOS_PG_SCHEMA_CURRICULUM", "curriculum")
    assert pg_sqlite.schema_for("curriculum", tmp_path / "a.sqlite") == "curriculum"
    monkeypatch.setenv("ACOS_PG_SCHEMA_CURRICULUM", "bad; drop")
    with pytest.raises(ValueError):
        pg_sqlite.schema_for("curriculum", tmp_path / "a.sqlite")


# ---- behaviour, against a real Postgres ----------------------------------------------------------

def _dsn():
    host = os.environ.get("ACOS_STORE_PG_HOST") or os.environ.get("ACOS_TEST_PG_HOST")
    if not host:
        return None
    pre = "ACOS_STORE_PG_" if os.environ.get("ACOS_STORE_PG_HOST") else "ACOS_TEST_PG_"
    return {"host": host, "port": os.environ.get(pre + "PORT", "5432"), "dbname": os.environ.get(pre + "DB", "postgres"),
            "user": os.environ.get(pre + "USER", "postgres"), "password": os.environ.get(pre + "PASSWORD", ""),
            "connect_timeout": "10"}


needs_pg = pytest.mark.skipif(_dsn() is None, reason="set ACOS_STORE_PG_HOST or ACOS_TEST_PG_HOST")


@pytest.fixture
def conn():
    c = pg_sqlite.Connection(f"t_{uuid.uuid4().hex[:12]}", _dsn())
    c.executescript("""
        CREATE TABLE IF NOT EXISTS sections (
          id TEXT PRIMARY KEY, grade TEXT NOT NULL, name TEXT NOT NULL COLLATE NOCASE,
          seats INTEGER, avg REAL, UNIQUE(grade, name));
        CREATE TABLE IF NOT EXISTS runs (job TEXT, period TEXT, n INTEGER, PRIMARY KEY (job, period));
    """)
    yield c
    c.rollback()
    c.execute(f"DROP SCHEMA {c.schema} CASCADE")
    c.commit()
    c.close()


@needs_pg
def test_a_failed_statement_leaves_the_transaction_as_sqlite_does(conn):
    conn.execute("INSERT INTO sections (id, grade, name) VALUES (?,?,?)", ("a", "10", "A"))
    with pytest.raises(sqlite3.IntegrityError, match="UNIQUE constraint failed"):
        conn.execute("INSERT INTO sections (id, grade, name) VALUES (?,?,?)", ("b", "10", "a"))
    conn.execute("INSERT INTO sections (id, grade, name) VALUES (?,?,?)", ("c", "10", "B"))
    conn.commit()
    assert [r["id"] for r in conn.execute("SELECT id FROM sections ORDER BY rowid").fetchall()] == ["a", "c"]


@needs_pg
def test_rows_are_sqlite_rows_and_values_loosely_typed(conn):
    conn.execute("INSERT INTO sections (id, grade, name, seats, avg) VALUES (?,?,?,?,?)", ("a", 10, "A", True, 1.5))
    r = conn.execute("SELECT * FROM sections WHERE grade = ?", (10,)).fetchone()
    assert dict(r) == {"id": "a", "grade": "10", "name": "A", "seats": 1, "avg": 1.5}
    assert r[0] == "a" and r["name"] == "A" and list(r.keys())[0] == "id"
    assert conn.execute("SELECT count(*), avg(seats), sum(seats) FROM sections").fetchone()[:] == (1, 1, 1)


@needs_pg
def test_or_replace_updates_on_the_primary_key_and_table_info_reads_columns(conn):
    for n in (1, 2):
        conn.execute("INSERT OR REPLACE INTO runs (job, period, n) VALUES (?,?,?)", ("j", "p", n))
    assert conn.execute("SELECT n FROM runs").fetchall()[0][0] == 2
    assert [r["name"] for r in conn.execute("PRAGMA table_info(runs)").fetchall()] == ["job", "period", "n"]


@needs_pg
def test_nulls_sort_first_and_text_sorts_by_bytes_as_in_sqlite(conn):
    for i, (g, seats) in enumerate([("b", 2), ("B", None), ("a", 1)]):
        conn.execute("INSERT INTO sections (id, grade, name, seats) VALUES (?,?,?,?)", (f"s{i}", g, f"n{i}", seats))
    assert [r[0] for r in conn.execute("SELECT seats FROM sections ORDER BY seats").fetchall()] == [None, 1, 2]
    assert [r[0] for r in conn.execute("SELECT grade FROM sections ORDER BY grade").fetchall()] == ["B", "a", "b"]
