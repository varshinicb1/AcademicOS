"""Backfill D1 `chunks.class_no` from the chunk pack.

The pack stores the grade under `class`, while the Worker read `class_no`, so the
column landed NULL for all 12,570 rows and every `class_no` filter in /search
silently matched nothing. The Worker is fixed to accept both spellings, but the
rows already in D1 still need the value.

Re-ingesting is not an option: Workers AI neurons are exhausted (9,011/9,000), and
re-embedding 12,570 chunks just to populate one integer column would spend a
quota we do not have. So this writes a `class_map` side table from the pack and
joins it in, which touches no vectors.

Usage:
    python backfill_class_no.py            # writes the SQL payload
    npx wrangler d1 execute academicos-corpus --remote --file class_no_backfill.sql
"""

from __future__ import annotations

import gzip
import json
import pathlib
import sqlite3

PACK = pathlib.Path(r"D:\wt\tagfix\corpus_build\chunks.jsonl.gz")
OUT = pathlib.Path(r"D:\wt\tagfix\workers\corpus-rag\class_no_backfill.sql")
BATCH = 500


def rows():
    with gzip.open(PACK, "rt", encoding="utf-8") as fh:
        for line in fh:
            r = json.loads(line)
            cls = r.get("class", r.get("class_no"))
            if cls is None:
                continue
            yield r["id"], int(cls)


def main() -> int:
    db = sqlite3.connect(":memory:")
    db.execute("CREATE TABLE class_map (id TEXT PRIMARY KEY, class_no INTEGER NOT NULL)")
    total = 0
    for cid, cls in rows():
        db.execute("INSERT OR REPLACE INTO class_map (id, class_no) VALUES (?, ?)", (cid, cls))
        total += 1
    db.commit()

    parts = [
        "-- Generated by scripts/corpus/backfill_class_no.py. Do not edit by hand.",
        "PRAGMA defer_foreign_keys = on;",
        "CREATE TABLE IF NOT EXISTS class_map (id TEXT PRIMARY KEY, class_no INTEGER NOT NULL);",
        "DELETE FROM class_map;",
    ]
    cur = db.execute("SELECT id, class_no FROM class_map")
    while rows_ := cur.fetchmany(BATCH):
        values = ", ".join(
            f"({i!r},{c})" for i, c in rows_
        )
        parts.append(f"INSERT OR REPLACE INTO class_map (id, class_no) VALUES {values};")
    parts.append(
        "UPDATE chunks SET class_no = ("
        "  SELECT m.class_no FROM class_map m WHERE m.id = chunks.id"
        ") WHERE id IN (SELECT id FROM class_map);"
    )
    parts.append("DROP TABLE class_map;")
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")

    print(f"pack rows with a class: {total}")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
